"""Writers for AlphaPulldown-compatible CPU-side input files."""

from __future__ import annotations

import csv
from pathlib import Path

from .screens import (
    Pair,
    control_pairs,
    full_screen_pairs,
    targeted_transport_pairs,
    write_pair_tsv,
)
from .targets import Target, filter_group, targets_by_id
from .validation import require, validate_accession


def validate_alphapulldown_spec(spec: str) -> None:
    parts = spec.split("+")
    require(len(parts) >= 1, f"Invalid AlphaPulldown spec: {spec}")
    for part in parts:
        validate_accession(part)


def write_sample_sheet(path: Path, pairs: list[Pair], targets: list[Target]) -> None:
    by_id = targets_by_id(targets)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = []
    for pair in pairs:
        spec = pair.alphapulldown_spec(by_id)
        validate_alphapulldown_spec(spec)
        lines.append(spec)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_accession_list(path: Path, targets: list[Target]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    accessions = []
    for target in targets:
        validate_accession(target.accession)
        accessions.append(target.accession)
    path.write_text("\n".join(accessions) + "\n", encoding="utf-8")


def write_alphapulldown_inputs(output_dir: Path, targets: list[Target]) -> list[Path]:
    output_dir.mkdir(parents=True, exist_ok=True)
    artifacts: list[Path] = []

    controls = control_pairs(targets)
    control_sheet = output_dir / "control_sample_sheet.csv"
    write_sample_sheet(control_sheet, controls, targets)
    artifacts.append(control_sheet)

    by_id = targets_by_id(targets)
    bait_targets = [by_id["HUMAN_DNAAF9"], by_id["HUMAN_DNAAF18"]]
    baits_file = output_dir / "transport_baits.txt"
    write_accession_list(baits_file, bait_targets)
    artifacts.append(baits_file)

    ift_b_targets = sorted(filter_group(targets, "IFT_B"), key=lambda item: item.record_id)
    preys_file = output_dir / "ift_b_preys.txt"
    write_accession_list(preys_file, ift_b_targets)
    artifacts.append(preys_file)

    control_pairs_path = output_dir / "control_pairs.tsv"
    write_pair_tsv(control_pairs_path, controls, targets)
    artifacts.append(control_pairs_path)

    transport_pairs_path = output_dir / "transport_pairs.tsv"
    write_pair_tsv(transport_pairs_path, targeted_transport_pairs(targets), targets)
    artifacts.append(transport_pairs_path)

    full_pairs_path = output_dir / "full_screen_pairs.tsv"
    write_pair_tsv(full_pairs_path, full_screen_pairs(targets), targets)
    artifacts.append(full_pairs_path)

    _write_readme(output_dir / "README.md")
    artifacts.append(output_dir / "README.md")
    return artifacts


def write_heavy_chain_review_table(path: Path, rows: list[dict[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=["record_id", "display_name", "accession", "length", "status", "reason"],
            delimiter="\t",
        )
        writer.writeheader()
        writer.writerows(rows)


def _write_readme(path: Path) -> None:
    path.write_text(
        "\n".join(
            [
                "# AlphaPulldown Prepared Inputs",
                "",
                "These files are generated by the CPU-side preparation pipeline.",
                "They use UniProt accession syntax for AlphaPulldown jobs.",
                "",
                "- `control_sample_sheet.csv`: explicit benchmark pair jobs.",
                "- `transport_baits.txt`: DNAAF9 and DNAAF18 baits.",
                "- `ift_b_preys.txt`: all verified IFT-B prey accessions.",
                "- `full_screen_pairs.tsv`: future full-screen pair definitions; do not execute "
                "blindly.",
                "",
            ]
        ),
        encoding="utf-8",
    )
